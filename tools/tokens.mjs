// Turns design/tokens.json into the dashboard's CSS variables and the phone app's Kotlin tokens, so the two can
// never drift (docs/superpowers/specs/2026-11-22-claude-look-design.md > Tokens).
//
//   node tools/tokens.mjs          write both
//   node tools/tokens.mjs --check  exit 1 if either is out of date

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = join(dirname(fileURLToPath(import.meta.url)), '..')
const t = JSON.parse(readFileSync(join(repo, 'design', 'tokens.json'), 'utf8'))
const cssFile = join(repo, 'ui', 'src', 'design', 'tokens.css')
const ktFile = join(repo, 'android', 'app', 'src', 'main', 'java', 'app', 'minihub', 'phone', 'ui', 'look', 'Tokens.kt')
const START = '/* tokens:start — generated by tools/tokens.mjs from design/tokens.json; do not edit by hand */'
const END = '/* tokens:end */'

const colors = Object.entries(t.colors)
const vars = theme => colors.map(([k, v]) => `  --${k}: ${v[theme].toLowerCase()};`).join('\n')

const css = [
  START,
  `:root,\n[data-theme='dark'] {\n${vars('dark')}\n  color-scheme: dark;\n}`,
  `[data-theme='light'] {\n${vars('light')}\n  color-scheme: light;\n}`,
  `:root {\n${Object.entries(t.sizes).map(([k, v]) => `  --${k}: ${v}px;`).join('\n')}\n${Object.entries(t.type)
    .map(([k, [s, l]]) => `  --t-${k}: ${s}px;\n  --t-${k}-lh: ${l}px;`)
    .join('\n')}\n}`,
  END,
].join('\n')

const camel = k => k.replace(/-(\w)/g, (_, c) => c.toUpperCase())
const argb = hex => `0xFF${hex.slice(1).toUpperCase()}.toInt()`
const kt = `// Generated by tools/tokens.mjs from design/tokens.json; do not edit by hand.
package app.minihub.phone.ui.look

/** The Claude look's colours for one theme. */
class Palette(
${colors.map(([k]) => `    val ${camel(k)}: Int,`).join('\n')}
    val dark: Boolean,
)

object Tokens {
    val DARK = Palette(
${colors.map(([k, v]) => `        ${camel(k)} = ${argb(v.dark)},`).join('\n')}
        dark = true,
    )

    val LIGHT = Palette(
${colors.map(([k, v]) => `        ${camel(k)} = ${argb(v.light)},`).join('\n')}
        dark = false,
    )

${Object.entries(t.sizes).map(([k, v]) => `    const val ${k.replace(/-/g, '_').toUpperCase()}_DP = ${v}`).join('\n')}

${Object.entries(t.type).map(([k, [s, l]]) => `    const val ${k.toUpperCase()}_SP = ${s}f\n    const val ${k.toUpperCase()}_LINE_SP = ${l}f`).join('\n')}
}
`

const currentCss = readFileSync(cssFile, 'utf8')
const a = currentCss.indexOf(START)
const b = currentCss.indexOf(END)
const nextCss = a >= 0 && b > a ? currentCss.slice(0, a) + css + currentCss.slice(b + END.length) : currentCss.replace("@import 'tailwindcss';", `@import 'tailwindcss';\n\n${css}`)

let currentKt = ''
try {
  currentKt = readFileSync(ktFile, 'utf8')
} catch {}

if (process.argv.includes('--check')) {
  const stale = [nextCss !== currentCss && cssFile, kt !== currentKt && ktFile].filter(Boolean)
  if (stale.length) {
    console.error(`Out of date (run npm run tokens):\n  ${stale.join('\n  ')}`)
    process.exit(1)
  }
  console.log('tokens: up to date')
} else {
  writeFileSync(cssFile, nextCss)
  writeFileSync(ktFile, kt)
  console.log('tokens: written')
}
